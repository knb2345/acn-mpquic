"""Train the bandwidth predictor and export it into TQUIC.

  train.py --placeholder                      write an untrained model (TRAINED = false)
  train.py <dataset.npz> [--use-q 0.2] [--seed 7]

The model is a small MLP (44 -> 32 -> 32 -> 4) that predicts quantiles of a
path's mean delivery capacity over the next HORIZON_MS, as ln(1 + kB/s), from
the features in features.py. It is trained with the pinball (quantile) loss in
numpy, so the deployed model is plain matrix arithmetic, and written to
third_party/tquic/src/multipath_scheduler/ml_model.rs as constants. The
scheduler uses the quantile given by --use-q: a low quantile is a cautious
estimate ("at least this much, most of the time").
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
OUT_RS = REPO / "third_party/tquic/src/multipath_scheduler/ml_model.rs"
N_IN, N_H = 44, 32
QUANTILES = [0.1, 0.2, 0.3, 0.5]
HORIZON_MS = 500


def init(rng):
    he = lambda o, i: (rng.standard_normal((o, i)) * np.sqrt(2.0 / i)).astype(np.float64)
    return {"W1": he(N_H, N_IN), "b1": np.zeros(N_H), "W2": he(N_H, N_H), "b2": np.zeros(N_H),
            "W3": he(len(QUANTILES), N_H) * 0.1, "b3": np.zeros(len(QUANTILES))}


def forward(p, x):
    a1 = x @ p["W1"].T + p["b1"]
    h1 = np.maximum(a1, 0)
    a2 = h1 @ p["W2"].T + p["b2"]
    h2 = np.maximum(a2, 0)
    return h2 @ p["W3"].T + p["b3"], (x, a1, h1, a2, h2)


def pinball(y, out, tau):
    e = y[:, None] - out
    return np.mean(np.maximum(tau * e, (tau - 1) * e), axis=0)


def grads(p, cache, y, out, tau):
    x, a1, h1, a2, h2 = cache
    n = len(y)
    e = y[:, None] - out
    d_out = np.where(e > 0, -tau, 1 - tau) / n  # d loss / d out, per quantile
    g = {"W3": d_out.T @ h2, "b3": d_out.sum(0)}
    d_h2 = d_out @ p["W3"] * (a2 > 0)
    g["W2"], g["b2"] = d_h2.T @ h1, d_h2.sum(0)
    d_h1 = d_h2 @ p["W2"] * (a1 > 0)
    g["W1"], g["b1"] = d_h1.T @ x, d_h1.sum(0)
    return g


def train(x_tr, y_tr, x_va, y_va, seed, epochs=200, batch=512, lr=2e-3, patience=20):
    rng = np.random.default_rng(seed)
    tau = np.array(QUANTILES)
    p = init(rng)
    m = {k: np.zeros_like(v) for k, v in p.items()}
    v = {k: np.zeros_like(val) for k, val in p.items()}
    best, best_p, bad, step = np.inf, None, 0, 0
    for ep in range(epochs):
        idx = rng.permutation(len(y_tr))
        for s in range(0, len(idx), batch):
            b = idx[s:s + batch]
            out, cache = forward(p, x_tr[b])
            g = grads(p, cache, y_tr[b], out, tau)
            step += 1
            for k in p:  # Adam
                m[k] = 0.9 * m[k] + 0.1 * g[k]
                v[k] = 0.999 * v[k] + 0.001 * g[k] ** 2
                p[k] -= lr * (m[k] / (1 - 0.9 ** step)) / (np.sqrt(v[k] / (1 - 0.999 ** step)) + 1e-8)
        val = pinball(y_va, forward(p, x_va)[0], tau).mean()
        if val < best - 1e-5:
            best, best_p, bad = val, {k: w.copy() for k, w in p.items()}, 0
        else:
            bad += 1
            if bad >= patience:
                break
    return best_p, best, ep + 1


def fmt(a):
    a = np.asarray(a, dtype=np.float32)
    if a.ndim == 1:
        return "[" + ", ".join(f"{x:.7e}" for x in a) + "]"
    return "[\n" + ",\n".join("    " + fmt(r) for r in a) + ",\n]"


def export(p, mean, std, use_q, trained, info, out_rs=OUT_RS):
    q = len(QUANTILES)
    src = f"""// Generated by analysis/ml/train.py; do not edit by hand.
// {info}

#![allow(clippy::excessive_precision, clippy::unreadable_literal)]

/// false: no trained model yet; the learned scheduler falls back to the
/// heuristic bandwidth estimate.
pub(crate) const TRAINED: bool = {str(trained).lower()};
pub(crate) const N_IN: usize = {N_IN};
pub(crate) const N_H: usize = {N_H};
pub(crate) const N_OUT: usize = {q};
/// Prediction horizon: mean capacity over the next HORIZON_MS milliseconds.
pub(crate) const HORIZON_MS: u64 = {HORIZON_MS};
pub(crate) const QUANTILES: [f32; N_OUT] = {fmt(QUANTILES)};
/// Index into QUANTILES of the estimate the scheduler uses.
pub(crate) const USE_Q: usize = {use_q};

pub(crate) static MEAN: [f32; N_IN] = {fmt(mean)};
pub(crate) static STD: [f32; N_IN] = {fmt(std)};
pub(crate) static W1: [[f32; N_IN]; N_H] = {fmt(p["W1"])};
pub(crate) static B1: [f32; N_H] = {fmt(p["b1"])};
pub(crate) static W2: [[f32; N_H]; N_H] = {fmt(p["W2"])};
pub(crate) static B2: [f32; N_H] = {fmt(p["b2"])};
pub(crate) static W3: [[f32; N_H]; N_OUT] = {fmt(p["W3"])};
pub(crate) static B3: [f32; N_OUT] = {fmt(p["b3"])};
"""
    out_rs.write_text(src)
    # TQUIC's CI checks rustfmt; format the generated file the same way.
    import subprocess
    subprocess.run(["rustfmt", "--edition", "2021", str(out_rs)], check=False)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dataset", nargs="?")
    ap.add_argument("--placeholder", action="store_true")
    ap.add_argument("--use-q", type=float, default=0.2)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--out-rs", type=Path, default=OUT_RS, help="where to write the Rust model")
    a = ap.parse_args()
    use_q = QUANTILES.index(a.use_q)

    if a.placeholder:
        z = {"W1": np.zeros((N_H, N_IN)), "b1": np.zeros(N_H), "W2": np.zeros((N_H, N_H)),
             "b2": np.zeros(N_H), "W3": np.zeros((len(QUANTILES), N_H)), "b3": np.zeros(len(QUANTILES))}
        export(z, np.zeros(N_IN), np.ones(N_IN), use_q, False, "placeholder, not trained", a.out_rs)
        print(f"wrote untrained placeholder to {a.out_rs}")
        return

    d = np.load(a.dataset)
    # Validate on whole network conditions the training set never saw.
    x, y, run = d["x"], d["y"], d["cond"]
    runs = np.unique(run)
    rng = np.random.default_rng(a.seed)
    va_runs = rng.choice(runs, size=max(1, len(runs) // 5), replace=False)
    va = np.isin(run, va_runs)
    mean = x[~va].mean(0)
    std = np.maximum(x[~va].std(0), 1e-3)
    xn = (x - mean) / std
    p, best, epochs = train(xn[~va], y[~va], xn[va], y[va], a.seed)
    out = forward(p, xn[va])[0]
    tau = np.array(QUANTILES)
    coverage = (y[va][:, None] <= out).mean(0)
    loss = pinball(y[va], out, tau)
    info = (f"trained on {int((~va).sum())} samples from {len(runs) - len(va_runs)} network conditions, "
            f"validated on {int(va.sum())} from {len(va_runs)} held-out conditions; {epochs} epochs; "
            f"val pinball {best:.4f}; "
            f"val coverage per quantile {np.round(coverage, 3).tolist()}")
    export(p, mean, std, use_q, True, info, a.out_rs)
    np.savez(Path(a.dataset).with_suffix(".model.npz"), mean=mean, std=std, quantiles=np.array(QUANTILES),
             use_q=use_q, **p)
    report = {"samples_train": int((~va).sum()), "samples_val": int(va.sum()), "conditions_val": va_runs.tolist(),
              "epochs": epochs, "quantiles": QUANTILES, "val_pinball": loss.round(4).tolist(),
              "val_coverage": coverage.round(3).tolist(), "use_q": a.use_q}
    Path(a.dataset).with_suffix(".train.json").write_text(json.dumps(report, indent=1))
    print(info)
    print(f"wrote {a.out_rs}")


if __name__ == "__main__":
    main()
